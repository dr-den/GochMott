package com.bilto.gochmott.search

/**
 * ТОЧНЫЙ порт `RU_STOPWORDS` и `index_words` из `tools/build_app_db_v5.py`.
 *
 * Сборщик не кладёт служебные слова в обратный индекс. Значит и запрос обязан
 * отбрасывать их ровно так же — иначе `HAVING COUNT(DISTINCT word) = :n`
 * не сойдётся никогда: у `цӀаста` перевод «на пя́тый день (после сегодняшнего)»,
 * в индексе лежат `пятый`, `день`, `после`, `сегодняшнего`, а запрос «на пятый
 * день» просит ещё и `на`, которого там нет и быть не должно.
 *
 * Оговорка сборщика повторена дословно: **служебные выбрасываются, только если
 * остаётся что-то ещё.** У союза `а` перевод — ровно «и», у `бу` — ровно «есть»;
 * выбросив их, мы сделали бы эти статьи ненаходимыми. С обеих сторон правило
 * одно, поэтому запрос «и» находит `а`.
 *
 * Список менять только вместе со сборщиком: разойдутся — обратный поиск начнёт
 * молча терять статьи.
 */
object RuStopWords {

    /**
     * 93 слова, как в сборщике. Часть записей мертва с обеих сторон одинаково:
     * `всё`, `её`, `ещё`, `та́к` не совпадут ни с чем, потому что сравнение идёт
     * с уже нормализованным словом (`ё`→`е`, ударение снято), а их `е`-формы
     * в списке и так есть. Оставлены ради дословности порта.
     */
    private val WORDS: Set<String> = setOf(
        "и", "в", "во", "на", "с", "со", "к", "ко", "о", "об", "обо", "от", "до",
        "по", "за", "из", "у", "не", "ни", "же", "ли", "бы", "что", "чего", "чему",
        "чем", "кто", "кого", "кому", "кем", "то", "та", "те", "тот", "та́к", "как",
        "так", "вот", "все", "всё", "весь", "вся", "был", "была", "было", "были",
        "быть", "есть", "его", "ее", "её", "их", "он", "она", "оно", "они", "мы",
        "вы", "ты", "мой", "моя", "свой", "своя", "этот", "эта", "это", "эти",
        "для", "при", "над", "под", "про", "без", "через", "или", "а", "но", "да",
        "там", "тут", "ещё", "еще", "уже", "лишь", "либо", "нибудь", "кое", "чей",
        "чья", "чьи", "который", "которая", "которые"
    )

    fun isStopWord(word: String): Boolean = word in WORDS

    /**
     * Слова, по которым сборщик строил индекс: длиннее одной буквы и не служебные.
     * Если после отбора ничего не осталось — берём всё, что было.
     */
    fun significant(words: List<String>): List<String> {
        val kept = words.filter { it.length > 1 && !isStopWord(it) }
        return kept.ifEmpty { words.filter { it.isNotEmpty() } }
    }
}
