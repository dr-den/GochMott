package com.bilto.gochmott.search

/**
 * Надстрочные знаки словаря Мациева.
 *
 * В `dict.db` текст лежит размеченным: чеченский с чёрточками долготы
 * (`ха̃дадала`), русский с ударениями (`ка́ждый раз`). Ключи поиска (`*_norm`,
 * `trans_index.word`) собраны отдельно и уже очищены, поэтому знаки снимаются
 * только для показа и для буфера обмена — обратная операция не нужна.
 *
 * Оба знака — комбинирующие кодпойнты, идущие ПОСЛЕ гласной, поэтому снимаются
 * простым фильтром. Важно, что здесь не трогаются `й` и `ё`: это самостоятельные
 * буквы, а не буква с диакритикой, и `й` в чеченском несёт долготу (`ий`, `уьй`,
 * `юьй`). По той же причине нельзя раскладывать строку в NFD.
 */
object Diacritics {

    /** Чёрточка долготы над гласной, U+0303. */
    const val LENGTH = '̃'

    /** Русское ударение, U+0301. */
    const val STRESS = '́'

    fun withoutLength(text: String?): String =
        text.orEmpty().filterNot { it == LENGTH }

    fun withoutStress(text: String?): String =
        text.orEmpty().filterNot { it == STRESS }

    /** Без обоих знаков — то, что уходит в буфер обмена и в поисковые ключи. */
    fun plain(text: String?): String =
        text.orEmpty().filterNot { it == LENGTH || it == STRESS }
}
