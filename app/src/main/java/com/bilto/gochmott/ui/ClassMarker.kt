package com.bilto.gochmott.ui

/**
 * Классный показатель к показу.
 *
 * В базе он лежит одной буквой — `в`, `й`, `б`, `д`, — и это не упрощение,
 * а необходимость: книги пишут его по-разному, и сборщик приводит их к общему
 * виду. Словарь 1997 года печатает связку `(ю)` 554 раза, 2017-й — голое `(й)`;
 * без приведения `ю` и `й` разъехались бы, и сшивка статей между книгами дала
 * бы ложное расхождение на каждой паре.
 *
 * На экране показываем полную форму — показатель со связкой:
 *
 *     в -> ву     б -> бу
 *     й -> ю      д -> ду
 *
 * `й` даёт именно `ю`, а не `йу`: показатель `й` и гласная связки `у` в чеченском
 * письме сливаются в одну букву. Так это и напечатано в самом словаре 1997 года —
 * `(ю)` встречается 554 раза, `(йу)` не встречается ни разу.
 *
 * Преобразование живёт в UI, а не в базе: в базе показатель нужен голым — по нему
 * сравниваются статьи разных книг (`lemma_links`) и строятся классные словоформы.
 */
object ClassMarker {

    private val WITH_COPULA = mapOf(
        "в" to "ву",
        "й" to "ю",
        "б" to "бу",
        "д" to "ду"
    )

    /** Один показатель. Незнакомое значение отдаём как есть — врать о нём нечего. */
    fun full(marker: String): String = WITH_COPULA[marker] ?: marker

    /** Список показателей одной строкой: `в`, `й` -> «ву, ю». */
    fun list(markers: List<String>): String = markers.joinToString(", ") { full(it) }
}
